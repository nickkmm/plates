"""/usuarios -- admin screen to list login accounts, create one, change its
roles and active flag, and reset its password; and /usuarios/roles, its
"Roles y permisos" section, to list roles, create a custom role, edit a
role's permissions and delete an unused custom role.

The rules (username format, password length, valid roles, no locking
yourself out, at least one active admin) live in app/core/service.py;
this module only reads the form, writes through app.core.db and commits.
There is no delete: deactivating a user is how access is removed, and
app.web.auth re-reads roles and the active flag on every request, so a
change applies on the user's next request.

Roles: admin is read-only (it always has every permission, see
app/core/permissions.py), so its page has no form and a POST is a 400.
Other system roles keep their label (a submitted one is ignored) but their
permissions can be edited; custom roles can change both and, with no users,
be deleted. Internal role names (generated by service.new_role_name) are
only used in URLs and form values, never shown as page text. Permission
edits apply on each holder's next request, like role changes.

@permission_required("users.manage"), seeded for admin only.
"""

from __future__ import annotations

import psycopg
from flask import (
    Blueprint,
    abort,
    current_app,
    flash,
    redirect,
    render_template,
    request,
    session,
    url_for,
)
from psycopg.rows import DictRow
from werkzeug.security import generate_password_hash

from app.auth import repository, service
from app.auth.decorators import permission_required
from app.auth.permissions import ADMIN_ROLE
from app.auth.repository import RoleRecord, UserRecord
from app.shared import db

bp = Blueprint("users", __name__)


def _role_labels(conn: psycopg.Connection[DictRow]) -> dict[str, str]:
    return {r.name: r.label for r in repository.list_roles(conn)}


def _get_user_or_404(conn: psycopg.Connection[DictRow], user_id: int) -> UserRecord:
    user = repository.get_user_by_id(conn, user_id)
    if user is None:
        abort(404)
    return user


def _render_edit(user: UserRecord, *, roles: list[str], active: bool, error: str | None = None):
    with db.get_conn() as conn:
        all_roles = repository.list_roles(conn)
    page = render_template(
        "user_form.html", user=user, all_roles=all_roles, selected_roles=roles, active=active,
        error=error,
    )
    return (page, 400) if error else page


@bp.get("/usuarios")
@permission_required("users.manage")
def users():
    with db.get_conn() as conn:
        rows = repository.list_users(conn)
        labels = _role_labels(conn)
    role_text = {
        u.id: ", ".join(sorted(labels[r] for r in u.roles)) or "Sin roles" for u in rows
    }
    return render_template("users.html", rows=rows, role_text=role_text)


@bp.route("/usuarios/nuevo", methods=["GET", "POST"])
@permission_required("users.manage")
def user_new():
    with db.get_conn() as conn:
        all_roles = repository.list_roles(conn)
    if request.method == "GET":
        return render_template("user_form.html", user=None, all_roles=all_roles, selected_roles=[])

    username = (request.form.get("username") or "").strip()
    password = request.form.get("password") or ""
    password_confirm = request.form.get("password_confirm") or ""
    roles = request.form.getlist("roles")

    def _rerender(error: str):
        return render_template(
            "user_form.html", user=None, all_roles=all_roles, selected_roles=roles,
            username=username, error=error,
        ), 400

    try:
        with db.get_conn() as conn:
            error = service.validate_new_user(
                conn, username=username, password=password, password_confirm=password_confirm,
                roles=roles,
            )
            if error:
                return _rerender(error)
            repository.create_user(
                conn, username=username, password_hash=generate_password_hash(password),
                roles=roles, assigned_by=session["user_id"],
            )
            conn.commit()
    except psycopg.errors.UniqueViolation:
        return _rerender(service.MSG_DUPLICATE_USERNAME)

    current_app.logger.info(
        "user created: by=%s user=%s roles=%s", session["user"], username, ",".join(sorted(set(roles)))
    )
    flash("Usuario creado.")
    return redirect(url_for("users.users"))


@bp.route("/usuarios/<int:user_id>", methods=["GET", "POST"])
@permission_required("users.manage")
def user_edit(user_id: int):
    with db.get_conn() as conn:
        user = _get_user_or_404(conn, user_id)
    if request.method == "GET":
        return _render_edit(user, roles=user.roles, active=user.active)

    roles = request.form.getlist("roles")
    active = request.form.get("active") is not None
    with db.get_conn() as conn:
        error = service.validate_user_update(
            conn, target=user, actor_id=session["user_id"], roles=roles, active=active,
        )
        if error is None:
            repository.set_user_roles(conn, user_id, roles, assigned_by=session["user_id"])
            repository.update_user(conn, user_id, active=active)
            conn.commit()
    if error:
        return _render_edit(user, roles=roles, active=active, error=error)

    current_app.logger.info(
        "user updated: by=%s user=%s roles=%s", session["user"], user.username, ",".join(sorted(set(roles)))
    )
    flash("Cambios guardados.")
    return redirect(url_for("users.user_edit", user_id=user_id))


@bp.post("/usuarios/<int:user_id>/password")
@permission_required("users.manage")
def user_password(user_id: int):
    with db.get_conn() as conn:
        user = _get_user_or_404(conn, user_id)
    password = request.form.get("password") or ""
    error = service.validate_password(password, request.form.get("password_confirm") or "")
    if error:
        return _render_edit(user, roles=user.roles, active=user.active, error=error)

    with db.get_conn() as conn:
        repository.set_user_password(conn, user_id, generate_password_hash(password))
        conn.commit()
    current_app.logger.info(
        "user password reset: by=%s user=%s roles=%s", session["user"], user.username, ",".join(user.roles)
    )
    flash("Contraseña actualizada.")
    return redirect(url_for("users.user_edit", user_id=user_id))


def _get_role_or_404(conn: psycopg.Connection[DictRow], name: str) -> RoleRecord:
    role = repository.get_role(conn, name)
    if role is None:
        abort(404)
    return role


def _render_role_form(
    role: RoleRecord | None, *, label: str, permissions: list[str], error: str | None = None
):
    with db.get_conn() as conn:
        all_permissions = repository.list_permissions(conn)
    page = render_template(
        "role_form.html", role=role, label=label, all_permissions=all_permissions,
        selected_permissions=permissions, is_admin=role is not None and role.name == ADMIN_ROLE,
        error=error,
    )
    return (page, 400) if error else page


@bp.get("/usuarios/roles")
@permission_required("users.manage")
def roles():
    with db.get_conn() as conn:
        rows = repository.list_roles(conn)
    return render_template("roles.html", rows=rows, admin_role=ADMIN_ROLE)


@bp.route("/usuarios/roles/nuevo", methods=["GET", "POST"])
@permission_required("users.manage")
def role_new():
    if request.method == "GET":
        return _render_role_form(None, label="", permissions=[])

    label = (request.form.get("label") or "").strip()
    name = service.new_role_name()
    try:
        with db.get_conn() as conn:
            permissions = service.clean_permissions(conn, request.form.getlist("permissions"))
            error = service.validate_role(conn, label=label, permissions=permissions)
            if error is None:
                repository.create_role(conn, name=name, label=label, permissions=permissions)
                conn.commit()
    except psycopg.errors.UniqueViolation:
        error = service.MSG_DUPLICATE_ROLE_LABEL
    if error:
        return _render_role_form(
            None, label=label, permissions=request.form.getlist("permissions"), error=error
        )

    current_app.logger.info("role created: by=%s role=%s", session["user"], name)
    flash("Rol creado.")
    return redirect(url_for("users.roles"))


@bp.route("/usuarios/roles/<name>", methods=["GET", "POST"])
@permission_required("users.manage")
def role_edit(name: str):
    with db.get_conn() as conn:
        role = _get_role_or_404(conn, name)
    if request.method == "GET":
        return _render_role_form(role, label=role.label, permissions=role.permissions)
    if role.name == ADMIN_ROLE:
        return _render_role_form(role, label=role.label, permissions=role.permissions), 400

    label = role.label if role.is_system else (request.form.get("label") or "").strip()
    try:
        with db.get_conn() as conn:
            permissions = service.clean_permissions(conn, request.form.getlist("permissions"))
            error = service.validate_role(conn, label=label, permissions=permissions, role_name=name)
            if error is None:
                repository.update_role(conn, name, label=label, permissions=permissions)
                conn.commit()
    except psycopg.errors.UniqueViolation:
        error = service.MSG_DUPLICATE_ROLE_LABEL
    if error:
        return _render_role_form(
            role, label=label, permissions=request.form.getlist("permissions"), error=error
        )

    current_app.logger.info("role updated: by=%s role=%s", session["user"], name)
    flash("Cambios guardados.")
    return redirect(url_for("users.role_edit", name=name))


@bp.post("/usuarios/roles/<name>/delete")
@permission_required("users.manage")
def role_delete(name: str):
    with db.get_conn() as conn:
        role = _get_role_or_404(conn, name)
    error = service.validate_role_delete(role)
    if error is None:
        try:
            with db.get_conn() as conn:
                repository.delete_role(conn, name)
                conn.commit()
        except psycopg.errors.ForeignKeyViolation:
            error = service.MSG_DELETE_ROLE_IN_USE
    if error:
        return _render_role_form(role, label=role.label, permissions=role.permissions, error=error)

    current_app.logger.info("role deleted: by=%s role=%s", session["user"], name)
    flash("Rol eliminado.")
    return redirect(url_for("users.roles"))
