"""Storage helpers for files uploaded through the public declaration form.

Files live in `uploads_dir()` (a Docker volume), are named with a random
uuid4 (never the client's filename) and are never served by a public URL: the
authenticated download route must go through `resolve_upload_path`.
"""

from __future__ import annotations

import base64
import binascii
import os
import re
import uuid
from pathlib import Path
from typing import Any

MAX_PDF_BYTES = 10 * 1024 * 1024
MAX_SIGNATURE_BYTES = 200 * 1024
PDF_MAGIC = b"%PDF-"
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"
PNG_DATA_URL_PREFIX = "data:image/png;base64,"
_STORED_NAME_RE = re.compile(r"[0-9a-f]{32}\.(pdf|png)")


class UploadError(ValueError):
    """Validation failure; the message is Spanish and safe to show the user."""


def uploads_dir() -> Path:
    path = Path(os.environ.get("UPLOADS_DIR", "/srv/uploads"))
    path.mkdir(parents=True, exist_ok=True)
    return path


def _store(content: bytes, extension: str) -> str:
    name = f"{uuid.uuid4().hex}.{extension}"
    (uploads_dir() / name).write_bytes(content)
    return name


def save_pdf(file_storage: Any) -> str:
    if file_storage is None:
        raise UploadError("Debe adjuntar el PDF autenticado.")
    # Read at most one byte over the limit so a huge upload is not fully loaded.
    content = file_storage.stream.read(MAX_PDF_BYTES + 1)
    if not content:
        raise UploadError("El archivo PDF está vacío.")
    if len(content) > MAX_PDF_BYTES:
        raise UploadError("El PDF supera el tamaño máximo de 10 MB.")
    if not content.startswith(PDF_MAGIC):
        raise UploadError("El archivo adjunto no es un PDF válido.")
    return _store(content, "pdf")


def save_signature_png(data_url: str) -> str:
    if not data_url or not isinstance(data_url, str):
        raise UploadError("Falta la firma.")
    if not data_url.startswith(PNG_DATA_URL_PREFIX):
        raise UploadError("La firma no tiene un formato válido.")
    encoded = data_url[len(PNG_DATA_URL_PREFIX) :]
    # Reject oversize before decoding (base64 inflates by 4/3).
    if len(encoded) > (MAX_SIGNATURE_BYTES * 4) // 3 + 8:
        raise UploadError("La firma es demasiado grande.")
    try:
        content = base64.b64decode(encoded, validate=True)
    except (binascii.Error, ValueError):
        raise UploadError("La firma no tiene un formato válido.") from None
    if not content:
        raise UploadError("Falta la firma.")
    if len(content) > MAX_SIGNATURE_BYTES:
        raise UploadError("La firma es demasiado grande.")
    if not content.startswith(PNG_MAGIC):
        raise UploadError("La firma no es una imagen PNG válida.")
    # Blank-canvas detection is intentionally skipped: it would require
    # decoding the PNG (no imaging dependency); the form enforces "signed" in JS.
    return _store(content, "png")


def resolve_upload_path(name: str) -> Path:
    """Map a stored name to its path, rejecting anything not generated by us."""
    if not isinstance(name, str) or not _STORED_NAME_RE.fullmatch(name):
        raise UploadError("Archivo no encontrado.")
    return uploads_dir() / name
